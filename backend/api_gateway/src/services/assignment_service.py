from datetime import date, timedelta
from typing import List, Optional, Tuple

from shared.schemas.core import (
    Assignment,
    AssignmentsRecurrencesResult,
    OccurrenceInfo,
    RecurrenceEndType,
    RecurrenceExclusion,
    RecurrenceRule,
    RecurrenceUpdateScope,
    Shift,
    ShiftType,
)

from src.services.base_service import BaseService
from src.utils.recurrence_utils import generate_recurring_dates


class AssignmentService(BaseService):
    def create_assignment_and_recurrence(
        self,
        assignment_new: Assignment,
        recurrence_new: Optional[RecurrenceRule] = None,
    ) -> AssignmentsRecurrencesResult:
        shift = self.collection.shift_db.get_shift_by_id(assignment_new.shift_id)
        if shift is None:
            raise ValueError(f"Shift with ID {assignment_new.shift_id} does not exist.")
        if recurrence_new:
            return self._handle_recurrence_and_assignments_creation(
                recurrence=recurrence_new,
                assignment=assignment_new,
                shift=shift,
            )

        out = AssignmentsRecurrencesResult(
            assignments_created=[],
            assignments_read=[],
            assignments_updated=[],
            assignments_deleted_ids=[],
            recurrence_created=None,
            recurrences_read=[],
            recurrence_updated=None,
            recurrences_deleted_ids=[],
        )

        assignment_saved = self.collection.assignment_db.create_assignment(
            assignment_new
        )
        out.assignments_created.append(assignment_saved)

        if shift.shift_type == ShiftType.DUTY:
            assignments_recup = self._create_recuperation_assignments(
                assignments_duty=out.assignments_created
            )
            out.assignments_created.extend(assignments_recup)
        return out

    def _create_recuperation_assignments(
        self, assignments_duty: List[Assignment]
    ) -> List[Assignment]:
        duty_to_recup_map = self._get_duty_id_to_recup_shift_mapping(
            assignments_duty=assignments_duty
        )
        assignments_recup = []
        for assignment in assignments_duty:
            if assignment.shift_id in duty_to_recup_map:
                assignments_recup.append(
                    Assignment(
                        id="",  # ID will be generated by the database
                        team_id=assignment.team_id,
                        schedule_id=assignment.schedule_id,
                        worker_id=assignment.worker_id,
                        date=assignment.date,
                        shift_id=duty_to_recup_map[assignment.shift_id],
                        fixed=assignment.fixed,
                        reference_assignment_id=assignment.id,
                        recurrence_rule_id=assignment.recurrence_rule_id,
                    )
                )
        return self.collection.assignment_db.create_assignments(assignments_recup)

    def _get_duty_id_to_recup_shift_mapping(
        self, assignments_duty: List[Assignment]
    ) -> dict:
        shift_duty_ids = {assignment.shift_id for assignment in assignments_duty}
        shift_recup = self.collection.shift_db.get_recuperation_shifts(
            shift_ids=list(shift_duty_ids)
        )
        duty_to_recup_map = {}
        for shift in shift_recup:
            duty_to_recup_map[shift.recuperation_duty_id] = shift.id

        return duty_to_recup_map

    # pylint: disable=too-many-arguments
    def _handle_recurrence_and_assignments_creation(
        self,
        recurrence: RecurrenceRule,
        assignment: Assignment,
        shift: Shift,
        create_recurrence: bool = True,
        create_first_assignment: bool = True,
    ) -> AssignmentsRecurrencesResult:
        out = AssignmentsRecurrencesResult(
            assignments_created=[],
            assignments_read=[],
            assignments_updated=[],
            assignments_deleted_ids=[],
            recurrence_created=None,
            recurrences_read=[],
            recurrence_updated=None,
            recurrences_deleted_ids=[],
        )
        if create_recurrence:
            recurrence.occurrence_info.worker_id = assignment.worker_id
            recurrence.occurrence_info.shift_id = assignment.shift_id
            recurrence = self.collection.recurrence_db.create_recurrence(recurrence)
            out.recurrence_created = recurrence
        assignments_recurrence = self._handle_recurrence_assignments_creation(
            recurrence=recurrence,
            create_first_assignment=create_first_assignment,
        )
        out.assignments_created.extend(assignments_recurrence)

        if create_first_assignment:
            existing_assignment = next(
                (
                    a
                    for a in out.assignments_created
                    if a.date == assignment.date
                    and a.worker_id == assignment.worker_id
                    and a.shift_id == assignment.shift_id
                ),
                None,
            )
            if not existing_assignment:
                assignment_saved = self.collection.assignment_db.create_assignment(
                    assignment
                )
                out.assignments_created.append(assignment_saved)

        if shift.shift_type == ShiftType.DUTY:
            assignments_recup = self._create_recuperation_assignments(
                assignments_duty=out.assignments_created
            )
            out.assignments_created.extend(assignments_recup)
        return out

    def _handle_recurrence_creation(
        self, recurrence: RecurrenceRule
    ) -> Tuple[RecurrenceRule, List[Assignment]]:
        recurrence_saved = self.collection.recurrence_db.create_recurrence(recurrence)
        assignments_recurrence = self._handle_recurrence_assignments_creation(
            recurrence=recurrence_saved
        )
        return (recurrence_saved, assignments_recurrence)

    def _handle_recurrence_assignments_creation(
        self, recurrence: RecurrenceRule, create_first_assignment: bool = True
    ) -> List[Assignment]:
        out: List[Assignment] = []
        schedule_wip = self.collection.schedule_db.get_schedule_campaign(
            team_id=recurrence.team_id
        )
        if schedule_wip:
            if (
                recurrence.occurrence_info.worker_id is None
                or recurrence.occurrence_info.shift_id is None
            ):
                raise ValueError(
                    "Recurrence must have a worker ID and a shift ID to create "
                    + "assignments."
                )
            dates_recurring = generate_recurring_dates(
                period_start=schedule_wip.start_date,
                period_end=schedule_wip.end_date,
                recurrence_rule=recurrence,
                exclusions=[],
            )
            if not create_first_assignment:
                dates_recurring = [
                    d for d in dates_recurring if d != recurrence.start_date
                ]
            assignments_rec_campaign = [
                Assignment(
                    id="",  # ID will be generated by the database
                    team_id=recurrence.team_id,
                    schedule_id=schedule_wip.id,
                    worker_id=recurrence.occurrence_info.worker_id,
                    date=date,
                    shift_id=recurrence.occurrence_info.shift_id,
                    fixed=True,
                    reference_assignment_id=None,
                    recurrence_rule_id=recurrence.id,
                )
                for date in dates_recurring
            ]
            out = self.collection.assignment_db.create_assignments(
                assignments_rec_campaign
            )
        return out

    def create_recuperation_assignments_upon_shift_duty_creation(
        self, shift_duty_id: str, shift_recup_id: str, team_id: str
    ) -> None:
        # fmt: off
        assignments_duty_recup = self.collection.assignment_db\
            .get_assignments_by_team_and_shifts_today_onward(
                team_id=team_id,
                shift_ids=[shift_duty_id, shift_recup_id],
            )
        # fmt: on

        # Separate assignments by shift
        assignments_duty = [
            assignment
            for assignment in assignments_duty_recup
            if assignment.shift_id == shift_duty_id
        ]
        assignments_recup_dict = {
            (assignment.worker_id, assignment.date): assignment
            for assignment in assignments_duty_recup
            if assignment.shift_id == shift_recup_id
        }

        # Create recuperation assignments if not already existing
        new_assignments = []
        for duty_assignment in assignments_duty:
            key = (duty_assignment.worker_id, duty_assignment.date)
            if key not in assignments_recup_dict:
                new_assignment = Assignment(
                    id="",  # ID will be generated by the database
                    team_id=duty_assignment.team_id,
                    schedule_id=duty_assignment.schedule_id,
                    worker_id=duty_assignment.worker_id,
                    date=duty_assignment.date,  # Adjust date if needed
                    shift_id=shift_recup_id,
                    fixed=duty_assignment.fixed,
                    reference_assignment_id=duty_assignment.id,
                )
                new_assignments.append(new_assignment)

        if new_assignments:
            self.collection.assignment_db.create_assignments(new_assignments)

    def get_assignments_and_recurrences(
        self,
        team_id: str,
        start_date: Optional[date] = None,
        end_date: Optional[date] = None,
    ) -> AssignmentsRecurrencesResult:
        if start_date is None or end_date is None:
            assignments = self.collection.assignment_db.get_assignments(team_id)
        else:
            assignments = self.collection.assignment_db.get_assignments_by_dates(
                team_id, start_date, end_date
            )
        recurrences = self.collection.recurrence_db.get_recurrences_by_team_id(
            team_id=team_id
        )
        return AssignmentsRecurrencesResult(
            assignments_created=[],
            assignments_read=assignments,
            assignments_updated=[],
            assignments_deleted_ids=[],
            recurrence_created=None,
            recurrences_read=recurrences,
            recurrence_updated=None,
            recurrences_deleted_ids=[],
        )

    def update_assignment_and_recurrence(
        self,
        assignment_new: Assignment,
        recurrence_update_scope: Optional[RecurrenceUpdateScope] = None,
        recurrence: Optional[RecurrenceRule] = None,
    ) -> AssignmentsRecurrencesResult:
        assignment_updated, assignment_old = self._update_main_assignment(
            assignment_new=assignment_new
        )
        (
            assignments_recup_created,
            assignments_recup_updated,
            assignments_recup_deleted_ids,
        ) = self._udpdate_recup_assignments(
            assignment_new=assignment_new, assignment_old=assignment_old
        )
        if recurrence_update_scope and recurrence:
            ar_result_rec_update = self._handle_recurrence_update(
                recurrence_update_scope=recurrence_update_scope,
                recurrence_new=recurrence,
                assignment=assignment_updated,
            )
            if ar_result_rec_update.recurrence_created:
                assignment_updated.recurrence_rule_id = (
                    ar_result_rec_update.recurrence_created.id
                )
                for ar_created in assignments_recup_created:
                    ar_created.recurrence_rule_id = (
                        ar_result_rec_update.recurrence_created.id
                    )
                for ar_updated in assignments_recup_updated:
                    ar_updated.recurrence_rule_id = (
                        ar_result_rec_update.recurrence_created.id
                    )
                self.collection.assignment_db.update_assignments(
                    assignments=[assignment_updated]
                    + assignments_recup_created
                    + assignments_recup_updated
                )

            ar_result_rec_update.assignments_created.extend(assignments_recup_created)
            ar_result_rec_update.assignments_updated.extend(
                [assignment_updated] + assignments_recup_updated
            )
            ar_result_rec_update.assignments_deleted_ids.extend(
                assignments_recup_deleted_ids
            )
            return ar_result_rec_update
        return AssignmentsRecurrencesResult(
            assignments_created=assignments_recup_created,
            assignments_read=[],
            assignments_updated=[assignment_updated] + assignments_recup_updated,
            assignments_deleted_ids=assignments_recup_deleted_ids,
            recurrence_created=None,
            recurrences_read=[],
            recurrence_updated=None,
            recurrences_deleted_ids=[],
        )

    def _update_main_assignment(
        self,
        assignment_new: Assignment,
    ) -> Tuple[Assignment, Assignment]:
        assignment_old = self.collection.assignment_db.get_assignment_by_id(
            assignment_new.id
        )
        if not assignment_old:
            raise ValueError(f"Assignment with ID {assignment_new.id} does not exist.")
        assignment_updated = self.collection.assignment_db.update_assignment(
            assignment=assignment_new
        )
        return assignment_updated, assignment_old

    def _udpdate_recup_assignments(
        self, assignment_new: Assignment, assignment_old: Assignment
    ) -> Tuple[List[Assignment], List[Assignment], List[str]]:
        assignments_recup_created: List[Assignment] = []
        assignments_recup_updated: List[Assignment] = []
        assignments_recup_deleted_ids: List[str] = []
        if assignment_old.shift_id == assignment_new.shift_id:
            if assignment_old.fixed != assignment_new.fixed:
                assignment_recup_old = (
                    self.collection.assignment_db.get_assignments_by_reference_id(
                        reference_id=assignment_old.id
                    )
                )
                for assignment in assignment_recup_old:
                    assignment.fixed = assignment_new.fixed
                    assignments_recup_updated.append(
                        self.collection.assignment_db.update_assignment(assignment)
                    )
            return (
                assignments_recup_created,
                assignments_recup_updated,
                assignments_recup_deleted_ids,
            )

        # Check if the shift type is changing
        shift_old = self.collection.shift_db.get_shift_by_id(assignment_old.shift_id)
        shift_new = self.collection.shift_db.get_shift_by_id(assignment_new.shift_id)

        if not shift_old or not shift_new:
            raise ValueError("Invalid shift ID provided.")

        if shift_old.shift_type == ShiftType.DUTY:
            assignments_recup_deleted_ids = (
                self.collection.assignment_db.delete_assignments_by_reference_id(
                    reference_id=assignment_old.id
                )
            )

        if shift_new.shift_type == ShiftType.DUTY:
            shift_recup_new = self.collection.shift_db.get_recuperation_shift(
                shift_id=assignment_new.shift_id
            )
            if shift_recup_new:
                recuperation_assignment = Assignment(
                    id="",  # ID will be generated by the database
                    team_id=assignment_new.team_id,
                    schedule_id=assignment_new.schedule_id,
                    worker_id=assignment_new.worker_id,
                    date=assignment_new.date,
                    shift_id=shift_recup_new.id,
                    fixed=assignment_new.fixed,
                    reference_assignment_id=assignment_new.id,
                )
                assignments_recup_created.append(
                    self.collection.assignment_db.create_assignment(
                        recuperation_assignment
                    )
                )
        return (
            assignments_recup_created,
            assignments_recup_updated,
            assignments_recup_deleted_ids,
        )

    def _handle_recurrence_update(
        self,
        recurrence_update_scope: RecurrenceUpdateScope,
        recurrence_new: RecurrenceRule,
        assignment: Assignment,
    ) -> AssignmentsRecurrencesResult:
        if recurrence_update_scope == RecurrenceUpdateScope.NONE:
            # Assignment did not have a recurrence, so we just update it
            # Do not create the assignment for the start date
            shift = self.collection.shift_db.get_shift_by_id(assignment.shift_id)
            if shift is None:
                raise ValueError(f"Shift with ID {assignment.shift_id} does not exist.")
            return self._handle_recurrence_and_assignments_creation(
                recurrence=recurrence_new,
                assignment=assignment,
                shift=shift,
                create_recurrence=True,
                create_first_assignment=False,
            )
        if recurrence_update_scope == RecurrenceUpdateScope.SINGLE:
            # Update single assignment (done outside of this method) and create
            # recurrence exception
            exclusion = RecurrenceExclusion(
                id="",  # ID will be generated by the database
                recurrence_rule_id=recurrence_new.id,
                excluded_date=assignment.date,
            )
            self.collection.recurrence_exclusion_db.create_recurrence_exclusion(
                exclusion
            )
            # TODO_: find solution in case we are changing the only assignment
            # for this recurrence
            return AssignmentsRecurrencesResult(
                assignments_created=[],
                assignments_read=[],
                assignments_updated=[],
                assignments_deleted_ids=[],
                recurrence_created=None,
                recurrences_read=[],
                recurrence_updated=None,
                recurrences_deleted_ids=[],
            )
        if recurrence_update_scope == RecurrenceUpdateScope.FUTURE:
            # Create new recurrence starting at the time of the assignment
            recurrence_created = RecurrenceRule(
                id="",  # ID will be generated by the database
                team_id=recurrence_new.team_id,
                occurrence_type=recurrence_new.occurrence_type,
                occurrence_info=OccurrenceInfo(
                    worker_id=assignment.worker_id,
                    shift_id=assignment.shift_id,
                ),
                repeat_every=recurrence_new.repeat_every,
                frequency_type=recurrence_new.frequency_type,
                week_days=recurrence_new.week_days,
                month_repeat_type=recurrence_new.month_repeat_type,
                recurrence_end_type=recurrence_new.recurrence_end_type,
                start_date=assignment.date,
                end_date=recurrence_new.end_date,
                number_of_occurrences=recurrence_new.number_of_occurrences,
            )
            recurrence_old = self.collection.recurrence_db.get_recurrence_by_id(
                recurrence_id=recurrence_new.id
            )
            if (
                recurrence_old.recurrence_end_type
                == RecurrenceEndType.NUMBER_OF_OCCURRENCES
                and recurrence_new.recurrence_end_type
                == RecurrenceEndType.NUMBER_OF_OCCURRENCES
                and recurrence_old.number_of_occurrences is not None
                and recurrence_new.number_of_occurrences
                == recurrence_old.number_of_occurrences
            ):
                dates_original_rec = generate_recurring_dates(
                    period_start=recurrence_old.start_date,
                    period_end=assignment.date,
                    recurrence_rule=recurrence_old,
                    exclusions=[],
                )
                past_occurrence_count = len(
                    [d for d in dates_original_rec if d < assignment.date]
                )
                recurrence_created.number_of_occurrences = max(
                    recurrence_old.number_of_occurrences - past_occurrence_count,
                    0,
                )

            # Update recurrence to end at date of assignment
            recurrence_old.recurrence_end_type = RecurrenceEndType.END_DATE
            recurrence_old.end_date = assignment.date + timedelta(days=-1)
            recurrence_updated = self.collection.recurrence_db.update_recurrence(
                recurrence_old
            )
            # Delete all future assignments for this recurrence
            # fmt: off
            deleted_assignments_ids = self.collection.assignment_db\
                .delete_assignments_by_recurrence_rule_id_from_date(
                    recurrence_rule_id=recurrence_new.id,
                    from_date=assignment.date + timedelta(days=1),
                )
            # fmt: on
            # Create new assignments for the new recurrence
            shift = self.collection.shift_db.get_shift_by_id(assignment.shift_id)
            if shift is None:
                raise ValueError(f"Shift with ID {assignment.shift_id} does not exist.")
            ar_result = self._handle_recurrence_and_assignments_creation(
                recurrence=recurrence_created,
                assignment=assignment,
                shift=shift,
                create_recurrence=True,
                create_first_assignment=False,
            )
            ar_result.assignments_deleted_ids.extend(deleted_assignments_ids)
            ar_result.recurrence_updated = recurrence_updated
            return ar_result
        if recurrence_update_scope == RecurrenceUpdateScope.ALL:
            recurrence_old = self.collection.recurrence_db.get_recurrence_by_id(
                recurrence_id=recurrence_new.id
            )
            # Update the recurrence
            recurrence_new.start_date = recurrence_old.start_date
            recurrence_new.occurrence_info.worker_id = assignment.worker_id
            recurrence_new.occurrence_info.shift_id = assignment.shift_id
            recurrence_updated = self.collection.recurrence_db.update_recurrence(
                recurrence_new
            )
            # Update all assignments for this recurrence (delete and create)
            assignments_deleted_ids = (
                self.collection.assignment_db.delete_assignments_by_recurrence_rule_id(
                    recurrence_rule_id=recurrence_updated.id
                )
            )
            shift = self.collection.shift_db.get_shift_by_id(assignment.shift_id)
            if shift is None:
                raise ValueError(f"Shift with ID {assignment.shift_id} does not exist.")
            assignment.date = recurrence_updated.start_date
            ar_result = self._handle_recurrence_and_assignments_creation(
                recurrence=recurrence_updated,
                assignment=assignment,
                shift=shift,
                create_recurrence=False,
                create_first_assignment=True,
            )
            ar_result.assignments_deleted_ids.extend(assignments_deleted_ids)
            ar_result.recurrence_updated = recurrence_updated
            return ar_result
        raise ValueError(f"Invalid recurrence update scope: {recurrence_update_scope}")

    def delete_assignment_and_recurrence(
        self,
        assignment_id: str,
        recurrence_id: Optional[str] = None,
        recurrence_update_scope: Optional[RecurrenceUpdateScope] = None,
    ) -> AssignmentsRecurrencesResult:
        ar_result = AssignmentsRecurrencesResult(
            assignments_created=[],
            assignments_read=[],
            assignments_updated=[],
            assignments_deleted_ids=[],
            recurrence_created=None,
            recurrences_read=[],
            recurrence_updated=None,
            recurrences_deleted_ids=[],
        )
        if recurrence_id and recurrence_update_scope:
            ar_result = self._handle_recurrence_delete(
                assignment_id=assignment_id,
                recurrence_rule_id=recurrence_id,
                recurrence_update_scope=recurrence_update_scope,
            )
        deleted_ids = self.collection.assignment_db.delete_assignments_by_reference_id(
            reference_id=assignment_id
        )
        ar_result.assignments_deleted_ids.extend(deleted_ids)
        if assignment_id not in ar_result.assignments_deleted_ids:
            self.collection.assignment_db.delete_assignment(assignment_id)
            ar_result.assignments_deleted_ids.append(assignment_id)
        return ar_result

    def _handle_recurrence_delete(
        self,
        assignment_id: str,
        recurrence_rule_id: str,
        recurrence_update_scope: RecurrenceUpdateScope,
    ) -> AssignmentsRecurrencesResult:
        assignment = self.collection.assignment_db.get_assignment_by_id(assignment_id)
        if not assignment:
            raise ValueError(f"Assignment with ID {assignment_id} does not exist.")
        if recurrence_update_scope == RecurrenceUpdateScope.SINGLE:
            # Delete single assignment (done outside of this method) and create
            # recurrence exception
            exclusion = RecurrenceExclusion(
                id="",  # ID will be generated by the database
                recurrence_rule_id=recurrence_rule_id,
                excluded_date=assignment.date,
            )
            self.collection.recurrence_exclusion_db.create_recurrence_exclusion(
                exclusion
            )
            return AssignmentsRecurrencesResult(
                assignments_created=[],
                assignments_read=[],
                assignments_updated=[],
                assignments_deleted_ids=[],
                recurrence_created=None,
                recurrences_read=[],
                recurrence_updated=None,
                recurrences_deleted_ids=[],
            )
        if recurrence_update_scope == RecurrenceUpdateScope.FUTURE:
            # Update recurrence to end at date of assignment
            recurrence = self.collection.recurrence_db.get_recurrence_by_id(
                recurrence_rule_id
            )
            if not recurrence:
                raise ValueError(
                    f"Recurrence rule with ID {recurrence_rule_id} does not exist."
                )
            recurrence.recurrence_end_type = RecurrenceEndType.END_DATE
            recurrence.end_date = assignment.date + timedelta(days=-1)
            recurrence_updated = self.collection.recurrence_db.update_recurrence(
                recurrence
            )
            # Delete all future assignments for this recurrence
            # fmt: off
            deleted_assignments_ids = self.collection.assignment_db\
                .delete_assignments_by_recurrence_rule_id_from_date(
                    recurrence_rule_id=recurrence.id,
                    from_date=assignment.date,
                )
            # fmt: on
            return AssignmentsRecurrencesResult(
                assignments_created=[],
                assignments_read=[],
                assignments_updated=[],
                assignments_deleted_ids=deleted_assignments_ids,
                recurrence_created=None,
                recurrences_read=[],
                recurrence_updated=recurrence_updated,
                recurrences_deleted_ids=[],
            )
        if recurrence_update_scope == RecurrenceUpdateScope.ALL:
            # Delete all assignments for this recurrence
            assignments_deleted_ids = (
                self.collection.assignment_db.delete_assignments_by_recurrence_rule_id(
                    recurrence_rule_id=recurrence_rule_id
                )
            )
            # Delete the exclusions for this recurrence
            # fmt: off
            self.collection.recurrence_exclusion_db\
                .delete_recurrence_exclusions_by_rule_id(
                    rule_id=recurrence_rule_id
                )
            # fmt: on
            # Delete the recurrence
            self.collection.recurrence_db.delete_recurrence(recurrence_rule_id)
            return AssignmentsRecurrencesResult(
                assignments_created=[],
                assignments_read=[],
                assignments_updated=[],
                assignments_deleted_ids=assignments_deleted_ids,
                recurrence_created=None,
                recurrences_read=[],
                recurrence_updated=None,
                recurrences_deleted_ids=[recurrence_rule_id],
            )
        raise ValueError(f"Invalid recurrence update scope: {recurrence_update_scope}")
